"""Pedir cuatro notas y calcular el promedio"""

not1= float(input("Ingrese la nota uno: "))
not2= float(input("Ingrese la nota dos: "))
not3= float(input("Ingrese la nota tres: "))
not4= float(input("Ingrese la nota cuatro: "))
promedio= (not1 + not2 + not3 + not4)/4
print ("el promedio es igual a: " , promedio)



